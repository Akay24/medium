import { spawn } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync, mkdirSync, chmodSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { SandboxSpec } from "./spec.js";

export interface SandboxRun {
  stdout: string;
  stderr: string;
  exitCode: number | null;
  timedOut: boolean;
  durationMs: number;
  truncated: boolean;
  workspace: string;
}

export interface CodeSandbox {
  readonly name: string;
  readonly available: boolean;
  readonly unavailableReason?: string | undefined;
  /** Materialize exact snippet bytes + optional harness, execute, capture everything. */
  execute(spec: SandboxSpec, files: { path: string; contents: string }[], entrypoint: string): Promise<SandboxRun>;
  cleanup(workspace: string): void;
}

/** Run a command capturing bounded output; shared by the docker executor. */
export function runCommand(
  cmd: string,
  args: string[],
  opts: { cwd: string; timeoutMs: number; maxOutputBytes: number; env?: Record<string, string> }
): Promise<{ stdout: string; stderr: string; exitCode: number | null; timedOut: boolean; truncated: boolean }> {
  return new Promise((resolve) => {
    const child = spawn(cmd, args, {
      cwd: opts.cwd,
      env: { ...process.env, ...opts.env },
      stdio: ["ignore", "pipe", "pipe"]
    });
    let stdout = "";
    let stderr = "";
    let truncated = false;
    let timedOut = false;
    const cap = opts.maxOutputBytes;
    child.stdout.on("data", (d: Buffer) => {
      if (stdout.length < cap) stdout += d.toString();
      else truncated = true;
    });
    child.stderr.on("data", (d: Buffer) => {
      if (stderr.length < cap) stderr += d.toString();
      else truncated = true;
    });
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, opts.timeoutMs);
    child.on("error", (err) => {
      clearTimeout(timer);
      resolve({ stdout, stderr: stderr + String(err), exitCode: null, timedOut, truncated });
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ stdout, stderr, exitCode: code, timedOut, truncated });
    });
  });
}

/**
 * Executes in a throwaway Docker container with hardened settings:
 * no privileged mode, no docker socket, read-only rootfs (feasible),
 * dropped capabilities, no-new-privileges, cpu/mem/pids/time limits,
 * no network by default, isolated temp workspace, cleanup.
 * Model-generated text never reaches a host shell: it is written to files
 * inside the workspace and the container runs only the spec's fixed command.
 */
export class DockerSandbox implements CodeSandbox {
  readonly name = "docker";
  public available = true;
  public unavailableReason: string | undefined;

  constructor(private readonly defaults: { networkEnabled: boolean; readonlyRootfs: boolean; dropAllCapabilities: boolean }) {}

  async probe(): Promise<void> {
    const result = await runCommand("docker", ["info", "--format", "ok"], {
      cwd: tmpdir(),
      timeoutMs: 10_000,
      maxOutputBytes: 10_000
    });
    this.available = result.exitCode === 0 && result.stdout.includes("ok");
    if (!this.available) {
      this.unavailableReason =
        "Docker Engine is not reachable (not installed or daemon not running). Code verification cannot run; code stays unexecuted.";
    }
  }

  async execute(
    spec: SandboxSpec,
    files: { path: string; contents: string }[],
    entrypoint: string
  ): Promise<SandboxRun> {
    const workspace = mkdtempSync(join(tmpdir(), "pipeline-sandbox-"));
    for (const file of files) {
      const target = join(workspace, file.path);
      mkdirSync(join(target, ".."), { recursive: true });
      writeFileSync(target, file.contents);
    }
    // The entry script is generated by the pipeline (never model text). Snippet bytes
    // are mounted read-only; setup commands (from the trusted, human-reviewed spec)
    // run in a writable copy under /tmp so installs cannot alter the article bytes.
    writeFileSync(
      join(workspace, ".entrypoint.sh"),
      [
        "#!/bin/sh",
        "set -eu",
        "mkdir -p /tmp/work",
        "cp -r /work/. /tmp/work/",
        "rm /tmp/work/.entrypoint.sh",
        "cd /tmp/work",
        ...spec.setup,
        spec.run,
        ""
      ].join("\n")
    );
    chmodSync(join(workspace, ".entrypoint.sh"), 0o755);

    const started = Date.now();
    const networkFlag = spec.networkEnabled ? "--network=bridge" : "--network=none";
    const capsFlag = this.defaults.dropAllCapabilities ? ["--cap-drop=ALL"] : [];
    const roFlag = this.defaults.readonlyRootfs ? ["--read-only", "--tmpfs", "/tmp:rw,size=256m"] : [];
    const args = [
      "run",
      "--rm",
      "--name", `pipeline-sandbox-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
      networkFlag,
      "--memory", `${spec.memoryMb}m`,
      "--cpus", String(spec.cpus),
      "--pids-limit", String(spec.pidsLimit),
      "--security-opt", "no-new-privileges",
      ...capsFlag,
      ...roFlag,
      "-v", `${workspace}:/work:ro`,
      "-w", "/work",
      spec.image,
      "/bin/sh", "/work/.entrypoint.sh"
    ];
    const result = await runCommand("docker", args, {
      cwd: workspace,
      timeoutMs: spec.timeoutMs,
      maxOutputBytes: spec.maxOutputBytes
    });
    return {
      ...result,
      durationMs: Date.now() - started,
      workspace
    };
  }

  cleanup(workspace: string): void {
    rmSync(workspace, { recursive: true, force: true });
  }
}
